import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { lstatSync, readFileSync, readlinkSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';

/**
 * Source manifest policy.
 *
 * Enumeration comes from `git ls-files -z`, so the manifest describes the
 * version-controlled source and can never be changed by an untracked scratch
 * file. `-z` also means Git emits raw path bytes instead of octal-escaped
 * quoted paths, which keeps non-ASCII filenames portable.
 */
const header = [
  '# DiffBeacon source manifest',
  '# Generated by `npm run manifest` from the Git index. Dependency, build, and Git-metadata output,',
  '# forensic recovery payloads, historical stage audit reports, and this manifest itself are excluded.',
  '',
];

const excludedPrefixes = ['.bootstrap/', '.bootstrap2/', 'docs/recovery/', 'docs/audits/'];

const excludedFiles = ['SOURCE_MANIFEST.txt', 'RECOVERY_STAGE0.md'];

function isExcluded(file) {
  return excludedFiles.includes(file) || excludedPrefixes.some((prefix) => file.startsWith(prefix));
}

export function trackedSourceFiles(root = process.cwd()) {
  const listing = execFileSync('git', ['ls-files', '--full-name', '-z'], {
    cwd: root,
    encoding: 'utf8',
    shell: false,
    windowsHide: true,
    maxBuffer: 8 * 1024 * 1024,
  });
  return (
    listing
      .split('\0')
      .filter((file) => file.length > 0)
      // Sort by UTF-8 bytes so the order is identical on every platform locale.
      .sort((left, right) => Buffer.compare(Buffer.from(left, 'utf8'), Buffer.from(right, 'utf8')))
      .filter((file) => !isExcluded(file))
  );
}

function trackedBlobBytes(root, file) {
  const absolute = path.join(root, file);
  // Git stores a symbolic link as a blob containing the link target. Hash that blob
  // representation rather than following the link into arbitrary host files. On a
  // checkout with core.symlinks=false the same path is already a regular file whose
  // contents are that target string, so both checkout modes produce the same digest.
  if (lstatSync(absolute).isSymbolicLink()) return readlinkSync(absolute, { encoding: 'buffer' });
  return readFileSync(absolute);
}

export function renderSourceManifest(root = process.cwd()) {
  const lines = trackedSourceFiles(root).map((file) => {
    const digest = createHash('sha256').update(trackedBlobBytes(root, file)).digest('hex');
    return `${digest}  ${file}`;
  });
  return `${[...header, ...lines].join('\n')}\n`;
}
